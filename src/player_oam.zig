            v.link_dma_var2().* = @as(t.uint16, bank2) *% 2;
            const oam_pos: usize = (@as(usize, (if (scratch_0_var != 0) kPlayerOam_Tab20B else kPlayerOam_Tab20A)[r4loc]) + @as(usize, v.sort_sprites_offset_into_oam_buffer().*)) >> 2;
            const zt = zCoordLow();
            v.oam_buf()[oam_pos].y = (@as(t.uint8, @bitCast(kPlayerOam_Spr2Y[j])) +% ycoord) -% zt;
