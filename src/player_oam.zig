                if (oam_pal != 0)
                    td = (td & ~@as(t.uint16, 0xe00)) | oam_pal;
                t.word(&v.oam_buf()[oam_pos].charnum).* = td;
                v.oam_buf()[oam_pos].x = oam_x;
                v.oam_buf()[oam_pos].y = oam_y;
                var xt2: t.uint16 = @as(t.uint16, xcoord) -% @as(t.uint16, oam_x);
                if (@as(t.int16, @bitCast(xt2)) < 0) xt2 = 0 -% xt2;
                v.bytewise_extended_oam()[oam_pos] = sr.r12 | @intFromBool(xt2 >= 0x80);
