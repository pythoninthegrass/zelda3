pub export fn LinkOam_DrawFootObject(r4loc: c_int, oam_x_in: t.uint8, oam_y_in: t.uint8) void { // 8daed1
    v.primary_water_grass_timer().* = (v.primary_water_grass_timer().* +% 1) & 0xf;
    if (v.primary_water_grass_timer().* >= 9) {
        v.primary_water_grass_timer().* = 0;
        v.secondary_water_grass_timer().* = (v.secondary_water_grass_timer().* +% 1) & 3;
        if (v.secondary_water_grass_timer().* == 3)
            v.secondary_water_grass_timer().* = 0;
    }

    const i: usize = @as(usize, v.link_direction_facing_mirror().* >> 1) + @as(usize, kShieldTypeToOffs[@as(usize, v.link_shield_type().*)]);

    const oam_x = oam_x_in +% @as(t.uint8, @bitCast(kOffsToShadowGivenDir_X[i]));
