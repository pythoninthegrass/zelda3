        var oam_x: t.uint8 = @as(t.uint8, @bitCast(kShieldStuff_x[r2])) +% xcoord;

        LinkOam_CalculateXOffsetRelativeLink(@bitCast(kShieldStuff_x[r2]));

        const oam_pal: t.uint16 = if ((v.link_palette_bits_of_oam().* >> 8) != 0) 0xa00 else 0x600;

        const oam_pos: usize = (@as(usize, (if (scratch_0_var != 0) kShieldStuff_oam_index_ptrs_1 else kShieldStuff_oam_index_ptrs_0)[r4loc]) + @as(usize, v.sort_sprites_offset_into_oam_buffer().*)) >> 2;

        var j: usize = @as(usize, sr.r6) * 3;
        var i: usize = 0;
        while (i != 3) : ({
            i += 1;
            j += 1;
        }) {
            const td_raw = kShieldStuff_OamData[j];
            if (td_raw == 0xffff) continue;
            const td = (td_raw & 0xc1ff) | oam_pal | v.oam_priority_value().*;
            t.word(&v.oam_buf()[oam_pos].charnum).* = td;
            t.word(&v.oam_buf()[oam_pos].x).* = @as(t.uint16, oam_x) | (@as(t.uint16, oam_y) << 8);
            v.bytewise_extended_oam()[oam_pos] = sr.r12 | @as(t.uint8, @truncate(v.bit9_of_xcoord().*));
            oam_x +%= 8;
            if (i == 1) {
                oam_x -%= 16;
                oam_y +%= 8;
