    //SwordStuff_fail
    if (v.link_shield_type().* != 0 and v.sram_progress_indicator().* != 0 and !LinkOam_SetEquipmentVRAMOffsets(@intCast(r2), &sr)) {
        const zcoord = zCoordLow();
