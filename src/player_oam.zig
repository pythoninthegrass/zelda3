        oam_pos = @intCast(LinkOam_CalculateSwordSparklePosition(@intCast(oam_pos), xcoord, ycoord));

        var j: usize = @as(usize, sr.r6) * 3;
        var i: usize = 0;
        while (i != 3) : ({
            i += 1;
            j += 1;
        }) {
            const td_base = kSwordTiledata[j];
            if (td_base != 0xffff) {
                var td = (td_base & ~@as(t.uint16, 0x3000)) | v.oam_priority_value().*;
                if ((td & 0xe00) != 0x200 and v.link_palette_bits_of_oam().* == 0)
