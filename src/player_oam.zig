            const q_raw = t.word(&kPlayerOam_Prio[bank2 >> 1]).*;
            const q: t.uint16 = if (bank2 & 1 != 0) q_raw << 4 else q_raw;
            t.word(&v.oam_buf()[oam_pos].charnum).* = (q & 0xc000) | v.oam_priority_value().* | v.link_palette_bits_of_oam().* | 0x14;
