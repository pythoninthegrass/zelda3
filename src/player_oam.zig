            ((v.link_item_in_hand().* & 5) == 0);
        if (do_set_offsets) {
            v.player_oam_y_offset().* = @bitCast(kSwordOamYOffs[r2]);
            v.player_oam_x_offset().* = @bitCast(kSwordOamXOffs[r2]);
        }
        var oam_pal: t.uint16 = 0;
        if (v.link_item_in_hand().* & 5 != 0) {
            std.debug.assert(v.link_state_bits().* == 0);
            oam_pal = @as(t.uint16, @as(t.uint8, @bitCast(kPlayerOam_Rod[@as(usize, v.eq_selected_rod().* -% 1)]))) << 8;
        }
        if (v.link_position_mode().* & 8 != 0 and v.current_item_y().* == 13)
