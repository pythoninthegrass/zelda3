        t.hibyte(v.overlay_index()).* = yv *% 4;
        yv = 8 +% yv;
    } else {
        t.hibyte(v.overlay_index()).* = v.secondary_water_grass_timer().* *% 4;
        yv = 5 +% v.secondary_water_grass_timer().*;
    }

    if (yv >= 11) {
        // OOB read in the original: kLinkShadows_Chardata only has 22 entries, so yv*2+1 would run
        // past the end; the original hardcodes these two values instead of indexing it.
        t.word(&v.oam_buf()[oam_pos + 0].charnum).* = (@as(t.uint16, 0x00) & ~@as(t.uint16, 0x3000)) | v.oam_priority_value_2().*;
