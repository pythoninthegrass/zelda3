                    t.word(&v.oam_buf()[oam_pos + 0].x).* = @as(t.uint16, oam_x_s) | (oam_y_full << 8);
                    t.word(&v.oam_buf()[oam_pos + 1].x).* = @as(t.uint16, oam_x_s +% 8) | (oam_y_full << 8);
                    v.bytewise_extended_oam()[oam_pos + 0] = 0;
                    v.bytewise_extended_oam()[oam_pos + 1] = 0;
                }
            }
        }
    }

    {
        const oam_pos: usize = (@as(usize, (if (scratch_0_var != 0) kLinkBody_oam_index_1 else kLinkBody_oam_index_0)[r4loc]) + @as(usize, v.sort_sprites_offset_into_oam_buffer().*)) >> 2;
        const j: usize = kLinkDmaGraphicsIndices[r2];
        v.link_dma_graphics_index().* = @as(t.uint16, @intCast(j)) *% 2;

        if (v.link_visibility_status().* != 12) {
            const zc = zCoordLow();
            const sp = &kLinkSpriteBodys[j];
            const oam_y: t.uint8 = (ycoord +% @as(t.uint8, @bitCast(sp.y))) -% zc;
            const oam_x: t.uint8 = xcoord +% @as(t.uint8, @bitCast(sp.x));
            const td: t.uint16 = @as(t.uint16, sp.tile) << 8;

            if ((td & 0xf000) != 0xf000) {
                t.word(&v.oam_buf()[oam_pos].charnum).* = (td & 0xf000) | v.oam_priority_value().* | v.link_palette_bits_of_oam().*;
                t.word(&v.oam_buf()[oam_pos].x).* = @as(t.uint16, oam_x) | (@as(t.uint16, oam_y) << 8);
                v.bytewise_extended_oam()[oam_pos] = 2 +% @as(t.uint8, @intFromBool(oam_x >= 0xf8));
            }
            if ((td << 4 & 0xf000) != 0xf000) {
                t.word(&v.oam_buf()[oam_pos + 1].charnum).* = ((td << 4) & 0xf000) | v.oam_priority_value().* | v.link_palette_bits_of_oam().* | 2;
                t.word(&v.oam_buf()[oam_pos + 1].x).* = @as(t.uint16, xcoord) | (@as(t.uint16, (ycoord -% zc) +% 8) << 8);
                v.bytewise_extended_oam()[oam_pos + 1] = 2;
            }
        }
    }

    var doorway_t: t.uint16 = undefined;
    var hide_shadow = true;
    const doorway_cond = v.is_standing_in_doorway().* != 0 and blk: {
        doorway_t = v.link_x_coord().* -% v.BG2HOFS_copy2().*;
        if (doorway_t < 4) break :blk true;
        if (doorway_t >= 252) break :blk true;
        doorway_t = v.link_y_coord().* -% v.BG2VOFS_copy2().*;
        if (doorway_t < 4) break :blk true;
        break :blk doorway_t >= 224;
    };
    const cond = doorway_cond or blk2: {
        hide_shadow = false;
        const c1 = v.submodule_index().* == 0 and v.countdown_for_blink().* != 0 and blk3: {
            v.countdown_for_blink().* -%= 1;
            break :blk3 v.countdown_for_blink().* >= 4;
        } and (v.countdown_for_blink().* & 1) == 0;
        break :blk2 c1 or v.link_visibility_status().* == 12 or v.link_cape_mode().* != 0;
    };
    if (cond) {
        const shadow_oam_pos: c_int = if (!hide_shadow and v.link_visibility_status().* != 12)
            @as(c_int, (if (scratch_0_var != 0) kShadow_oam_indexes_1 else kShadow_oam_indexes_0)[r4loc]) >> 2
        else
            -10;

        // This appears to hide link by setting the extended bits of the oam to hide them from the screen.
        // It doesn't really play well with the widescreen modes, so change how it's done.
        if (enhanced_features0().* & kFeatures0_WidescreenVisualFixes != 0) {
            const oam_base: usize = @as(usize, v.sort_sprites_offset_into_oam_buffer().*) >> 2;
            var i: usize = 0;
            while (i < 12) : (i += 1) {
                if (@as(c_int, @intCast(i)) < shadow_oam_pos or @as(c_int, @intCast(i)) > shadow_oam_pos + 1)
                    v.oam_buf()[oam_base + i].y = 0xf0;
            }
        } else {
            const p_base: usize = @as(usize, v.sort_sprites_offset_into_oam_buffer().*) >> 2;
            t.word(&v.bytewise_extended_oam()[p_base + 0]).* = 0x101;
            t.word(&v.bytewise_extended_oam()[p_base + 2]).* = 0x101;
            t.word(&v.bytewise_extended_oam()[p_base + 4]).* = 0x101;
            t.word(&v.bytewise_extended_oam()[p_base + 6]).* = 0x101;
            t.word(&v.bytewise_extended_oam()[p_base + 8]).* = 0x101;
            t.word(&v.bytewise_extended_oam()[p_base + 10]).* = 0x101;
            // Clear the bit again for the shadow oam so it's not hidden?
            if (shadow_oam_pos >= 0)
                t.word(&v.bytewise_extended_oam()[p_base + @as(usize, @intCast(shadow_oam_pos))]).* = 0;
        }
    }

    if (v.submodule_index().* == 18 or v.submodule_index().* == 19)
        v.link_y_coord().* = y_coord_backup;
}

pub export fn FindMostSignificantBit(val_in: t.uint8) t.uint8 { // 8daac3
    var val = val_in;
    var i: i32 = 7;
    while (val & 0x80 == 0) {
        i -= 1;
        if (i < 0) break;
        val <<= 1;
    }
    return @bitCast(@as(i8, @truncate(i)));
}

pub export fn LinkOam_SetWeaponVRAMOffsets(r2: c_int, sr: *SwordResult) bool { // 8dab6e
    const idx: usize = @intCast(r2);
    const j: t.uint8 = @bitCast(kPlayerOam_Main_SwordStuff_array1[idx]);
    sr.r6 = j;
    if (j == 0xff) return true;
    sr.r12 = kPlayerOam_Main_SwordStuff_array2[@as(usize, j)];
    var y = kPlayerOam_Main_SwordStuff_array3[@as(usize, j)];
    if (j < 29) {
        v.link_dma_var3().* = y;
    } else {
        if (v.link_item_in_hand().* & 5 != 0)
            y = kPlayerOam_Main_SwordStuff_array4[@as(usize, j -% 29)];
        v.link_dma_var5().* = y;
    }
    return false;
}

