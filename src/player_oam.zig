// misc.h: FindInByteArray dropped its redundant size param — Zig slices
// carry their own length.
fn FindInByteArray(data: []const t.uint8, lookfor: t.uint8) i32 {
    var i: usize = data.len;
    while (i != 0) {
        i -= 1;
        if (data[i] == lookfor) return @intCast(i);
    }
    return -1;
}

