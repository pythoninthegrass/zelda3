        v.link_dma_var4().* = y;
        sr.r12 = 2;
    }
    return false;
}

pub export fn LinkOam_CalculateSwordSparklePosition(oam_pos: c_int, oam_x_in: t.uint8, oam_y_in: t.uint8) c_int { // 8dacd5
    if (v.link_player_handler_state().* | v.link_speed_setting().* != 0)
        return oam_pos;
    if (v.link_sword_type().* == 0 or v.link_sword_type().* == 1 or v.link_sword_type().* == 0xff or
        (v.button_mask_b_y().* & 0x80) == 0 or v.button_b_frames().* >= 9)
        return oam_pos;

    const i: usize = @as(usize, v.link_direction_facing().* >> 1) * 9 + @as(usize, v.button_b_frames().*);
    var td = kSwordTipSomething[i];
    if (td == 0xffff)
        return oam_pos;
    td = (td & ~@as(t.uint16, 0x3000)) | v.oam_priority_value().*;
    if (v.link_palette_bits_of_oam().* == 0)
        td = (td & ~@as(t.uint16, 0xe00)) | 0x600;
    const pos: usize = @intCast(oam_pos);
    t.word(&v.oam_buf()[pos].charnum).* = td;
    v.player_oam_x_offset().* = @bitCast(kSwordOamXOffs_Good[i]);
    v.player_oam_y_offset().* = @bitCast(kSwordOamYOffs_Good[i]);
    const oam_x = oam_x_in +% v.player_oam_x_offset().*;
    const oam_y = oam_y_in +% v.player_oam_y_offset().*;
    v.oam_buf()[pos].x = oam_x;
    v.oam_buf()[pos].y = oam_y;
    LinkOam_CalculateXOffsetRelativeLink(v.player_oam_x_offset().*);
    v.bytewise_extended_oam()[pos] = @truncate(v.bit9_of_xcoord().*);
    return oam_pos + 1;
}

