                if (oam_y_full < 256) {
                    const oam_x_s: t.uint8 = xcoord +% @as(t.uint8, @bitCast(kOffsToShadowGivenDir_X[@as(usize, v.link_direction_facing_mirror().* >> 1)]));
                    const oam_pos: usize = (@as(usize, (if (scratch_0_var != 0) kShadow_oam_indexes_1 else kShadow_oam_indexes_0)[r4loc]) + @as(usize, v.sort_sprites_offset_into_oam_buffer().*)) >> 2;

                    var td: t.uint16 = (kLinkShadows_Chardata[shadow_idx * 2] & ~@as(t.uint16, 0x3000)) | v.oam_priority_value_2().*;
                    if (v.link_palette_bits_of_oam().* == 0)
